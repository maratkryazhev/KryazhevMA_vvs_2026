def fix(test):
    w = test.strip()
    w = w.capitalize()
    w = w.replace('. ', '.').replace('.', '. ')
    w = w.replace(', ', ',').replace(',', ', ')
    w = w.replace(': ', ':').replace(':', ': ')
    w = w.replace('; ', ';').replace(';', '; ')
    w = w.replace('! ', '!').replace('!', '! ')
    w = w.replace('? ', '?').replace('?', '? ')
    w = w.strip()
    while '  ' in w:
        w = w.replace('  ', ' ')
    res = []
    for i in range(len(w)):
        if i >= 2 and w[i-2] in '.!?' and w[i-1] == ' ':
            res.append(w[i].upper())
        elif i < len(w)-1 and w[i] == ' ' and w[i+1] in '.!?;:,':
            pass
        else:
            res.append(w[i])
    wnew = ''.join(res)
    return wnew

