    try:
        n = int(input())
        if n < 1 or n > 2:
            print('Данные некорректны!')
        else:
            if n == 1:
                s = str(input('Введите исходную строку: '))
                r = str(input('Введите разделитель (пробел тоже нужно ввести!): '))
                print('Результат:', s.split(r))
            else:
                k = int(input('Введите количество элементов исходного списка: '))
                if k < 1:
                    print('Данные некорректны!')
                else:
                    print('Теперь по одному вводите каждый элемент:')
                    arr = []
                    for _ in range(k):
                        arr.append(input())
                    r = str(input('Введите разделитель (может отсутствовать): '))
                    print('Результат:', r.join(arr))
    except ValueError:
        print('Данные некорректны!')

