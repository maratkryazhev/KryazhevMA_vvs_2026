def summa(a, b):
    '''возвращает сумму двух чисел'''
    return (a+b)

def raznost(a, b):
    '''возвращает разность двух чисел'''
    return (a-b)

def proizvedenie(a, b):
    '''возвращает произведение двух чисел'''
    return (a*b)

def delenie(a, b):
    '''возвращает результат деления'''
    return (a/b)
